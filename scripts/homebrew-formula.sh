#!/usr/bin/env bash
# Writes the Homebrew formula for a release from its SHA256SUMS:
#   scripts/homebrew-formula.sh 0.2.0 dist/SHA256SUMS > Formula/overhive.rb
# Users install with:  brew tap abhijeetsinghjat/overhive https://github.com/Abhijeetsinghjat/overhive
#                      brew install overhive
set -euo pipefail
version="$1"; sums="$2"
sha() { awk -v f="overhive-$version-$1.tar.gz" '$2 == f { print $1 }' "$sums"; }
arm="$(sha osx-arm64)"; intel="$(sha osx-x64)"
[[ -n "$arm" && -n "$intel" ]] || { echo "missing macOS archives in $sums" >&2; exit 1; }
base="https://github.com/Abhijeetsinghjat/overhive/releases/download/v$version"
cat <<RUBY
# Generated by scripts/homebrew-formula.sh for v$version. Do not edit by hand.
class Overhive < Formula
  desc "Local mission control for AI coding agents (beta)"
  homepage "https://github.com/Abhijeetsinghjat/overhive"
  version "$version"
  license "Apache-2.0"

  on_arm do
    url "$base/overhive-$version-osx-arm64.tar.gz"
    sha256 "$arm"
  end
  on_intel do
    url "$base/overhive-$version-osx-x64.tar.gz"
    sha256 "$intel"
  end

  def install
    libexec.install "amcd", "cli"
    bin.write_exec_script libexec/"amcd/amcd"
    (bin/"overhive").write_exec_script libexec/"cli/agentctl"
    (bin/"agentctl").write_exec_script libexec/"cli/agentctl"
  end

  service do
    run [opt_bin/"amcd"]
    environment_variables MALLOC_ARENA_MAX: "2" # glibc (Linuxbrew) only; see scripts/amcd.service
    keep_alive crashed: true
    log_path var/"log/overhive.log"
    error_log_path var/"log/overhive.log"
  end

  def caveats
    <<~EOS
      Start Overhive now and at every login:
        brew services start overhive
      Then open http://127.0.0.1:47821
    EOS
  end

  test do
    assert_match "Overhive", shell_output("#{bin}/overhive version")
  end
end
RUBY
