#!/usr/bin/env bash
# Writes the Scoop manifest for a release from its SHA256SUMS (the Windows counterpart of homebrew-formula.sh):
#   scripts/scoop-manifest.sh 0.3.0 dist/SHA256SUMS > bucket/overhive.json
# Users install with:  scoop bucket add overhive https://github.com/Abhijeetsinghjat/overhive
#                      scoop install overhive
# The manifest also has checkver/autoupdate, so `checkver.ps1 -Update` from Scoop can refresh it later.
set -euo pipefail
version="$1"; sums="$2"
zip="overhive-$version-win-x64.zip"
hash="$(awk -v f="$zip" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
[[ -n "$hash" ]] || { echo "missing $zip in $sums" >&2; exit 1; }
repo="https://github.com/Abhijeetsinghjat/overhive"
cat <<JSON
{
    "##": "Generated by scripts/scoop-manifest.sh for v$version. Do not edit by hand.",
    "version": "$version",
    "description": "Local mission control for AI coding agents (beta, native Windows is an early preview)",
    "homepage": "$repo",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$repo/releases/download/v$version/$zip",
            "hash": "$hash",
            "extract_dir": "overhive-$version-win-x64"
        }
    },
    "bin": [
        [
            "cli\\\\agentctl.exe",
            "overhive"
        ],
        "cli\\\\agentctl.exe",
        "amcd\\\\amcd.exe"
    ],
    "post_install": "& \"\$dir\\\\install-release.ps1\" -InPlace",
    "pre_uninstall": "& \"\$dir\\\\install-release.ps1\" -InPlace -Uninstall",
    "notes": [
        "Overhive starts at logon through the per-user scheduled task 'Overhive'. Dashboard: http://127.0.0.1:47821",
        "Before 'scoop update overhive', stop the daemon: Stop-ScheduledTask Overhive",
        "AI-tool settings were not changed; connect your tools with: overhive hooks install"
    ],
    "checkver": {
        "url": "https://api.github.com/repos/Abhijeetsinghjat/overhive/releases",
        "jsonpath": "\$[0].tag_name",
        "regex": "v([\\\\d.]+)"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$repo/releases/download/v\$version/overhive-\$version-win-x64.zip",
                "extract_dir": "overhive-\$version-win-x64"
            }
        },
        "hash": {
            "url": "\$baseurl/SHA256SUMS"
        }
    }
}
JSON
